// Every dictionary value above is plain data (no functions) so the whole
// object can safely cross the Server -> Client Component boundary as a prop.
// Templates like "{name}" are filled in with this instead.
export function formatMessage(template: string, vars: Record<string, string>): string {
  return template.replace(/\{(\w+)\}/g, (match, key) => vars[key] ?? match);
}
